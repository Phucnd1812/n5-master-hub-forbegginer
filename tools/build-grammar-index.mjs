import {readFile,writeFile} from 'node:fs/promises';
import {COURSE} from '../assets/grammar/course.js';
import {COMPARISONS} from '../assets/grammar/comparisons.js';
import {EXTENSIONS,EXTENSION_ALIASES} from '../assets/grammar/extensions.js';
import {GRAMMAR_GUIDES,COURSE_ALIASES} from '../assets/search/grammar-data.js';

const target = new URL('../assets/grammar/search-data.js',import.meta.url);
const stripExamples = examples => examples.map(([jp,kana,vi]) => [jp,kana,vi]);
const topics = [
  ...GRAMMAR_GUIDES.map(({id,title,meaning,formula,aliases,examples}) =>
    ({id,title,meaning,formula,aliases,examples:stripExamples(examples)})),
  ...EXTENSIONS.map(([id,title,formula,meaning,,,,,examples]) =>
    ({id,title,formula,meaning,aliases:EXTENSION_ALIASES[id],examples:stripExamples(examples)})),
  ...COMPARISONS.map(([key,title,aliases,,meaning,sides]) =>
    ({id:'compare:' + key,title,meaning,
      aliases:[...aliases,sides.map(side => side[0]).join('と'),sides.map(side => side[0]).join(' ')],
      examples:stripExamples(sides.map(side => side[2]))})),
];
const lessons = COURSE.map(([id,title,formula,meaning,,,,,examples]) =>
  ({id,title,formula,meaning,aliases:COURSE_ALIASES[id] || [],examples:stripExamples(examples)}));
const output = '// Generated by tools/build-grammar-index.mjs. Edit the teaching sources instead.\n' +
  [['SEARCH_TOPICS',topics],['SEARCH_LESSONS',lessons]].map(([label,rows]) =>
    'export const ' + label + ' = [\n' + rows.map(row => '  ' + JSON.stringify(row) + ',').join('\n') + '\n];\n'
  ).join('\n');
if (process.argv.includes('--check')) {
  if (await readFile(target,'utf8') !== output) {
    process.exitCode = 1;
    console.error('Grammar search index is out of date.');
  }
} else await writeFile(target,output);
